create or replace function public.ms_workspace_snapshot(p_site text default null)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare v_admin boolean; v_sites jsonb; v_jobs jsonb;
begin
  if auth.uid() is null then raise exception 'not_allowed'; end if;
  v_admin := public.ms_is_admin();
  if p_site is not null and not public.ms_workspace_allowed(p_site) then raise exception 'not_allowed'; end if;
  select coalesce(jsonb_agg(jsonb_build_object(
    'slug',s.slug,'name',s.name,'url',s.url,'status',s.status,
    'service_package',coalesce(p.service_package,'package_1'),
    'sector',coalesce(p.sector,'general'),'relationship',coalesce(p.relationship,'client'),
    'showcase',coalesce(p.showcase,false),
    'connections',coalesce((select jsonb_agg(jsonb_build_object(
      'service',c.service,'state',c.state,'checked_at',c.checked_at,'error_code',c.error_code
    ) order by c.service) from public.ms_service_connections c where c.site=s.slug),'[]'::jsonb),
    'requests',coalesce((select jsonb_agg(jsonb_build_object(
      'id',r.id,'kind',r.kind,'target',r.target,'request',r.request,'status',r.status,
      'created_at',r.created_at,'done_at',r.done_at,
      'review_status',(select v.decision from public.ms_change_reviews v where v.change_id=r.id),
      'revision_note',(select v.note from public.ms_change_reviews v where v.change_id=r.id and v.decision='revision_requested')
    ) order by r.created_at desc) from (
      select * from public.ms_changes where site=s.slug and status<>'withdrawn' order by created_at desc limit 30
    ) r),'[]'::jsonb),
    'quota',(select to_jsonb(q) from public.ms_quota(s.slug) q)
  ) order by s.name),'[]'::jsonb) into v_sites
  from public.ms_sites s left join public.ms_site_profiles p on p.site=s.slug
  where (p_site is null or s.slug=p_site) and public.ms_workspace_allowed(s.slug);
  if v_admin then
    select coalesce(jsonb_agg(to_jsonb(j) - 'reviewed_by' - 'token' - 'artifact_html'),'[]'::jsonb) into v_jobs
    from (select * from public.ms_draft_jobs order by created_at desc limit 50) j;
  else v_jobs := '[]'::jsonb; end if;
  return jsonb_build_object('admin',v_admin,'sites',v_sites,'jobs',v_jobs);
end $$;
revoke all on function public.ms_workspace_snapshot(text) from public,anon,authenticated;
grant execute on function public.ms_workspace_snapshot(text) to authenticated;

