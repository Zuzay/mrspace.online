create or replace function public.ms_submit_intake(p_token uuid,p_name text,p_business text,p_email text,p_phone text,p_sector text,p_answers jsonb,p_sender_hash text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_id bigint;
begin
  if p_token is null or length(trim(coalesce(p_name,''))) not between 2 and 120
    or length(trim(coalesce(p_business,''))) not between 2 and 120
    or p_sender_hash is null or p_sender_hash !~ '^[a-f0-9]{64}$'
    or p_answers is null or jsonb_typeof(p_answers)<>'object' or octet_length(p_answers::text)>20000
    or length(coalesce(p_email,''))>200 or length(coalesce(p_phone,''))>80
    or (nullif(trim(p_email),'') is null and length(trim(coalesce(p_phone,'')))<5)
    or (nullif(trim(p_phone),'') is not null and (p_phone !~ '^[+0-9().[:space:]-]{5,80}$' or length(regexp_replace(p_phone,'[^0-9]','','g'))<5))
    or (nullif(trim(p_email),'') is not null and p_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$')
    or p_sector is null or p_sector not in('general','retail','fashion','food','services','community') then raise exception 'invalid_application'; end if;
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_sender_hash,71823));
  select id into v_id from public.ms_intakes where token=p_token;
  if v_id is not null then return jsonb_build_object('ok',true,'id',v_id,'duplicate',true); end if;
  if (select count(*) from public.ms_intakes where sender_hash=p_sender_hash and created_at>now()-interval '1 hour')>=5 then raise exception 'too_many'; end if;
  insert into public.ms_intakes(token,name,business,email,phone,sector,answers,sender_hash)
  values(p_token,trim(p_name),trim(p_business),nullif(trim(p_email),''),nullif(trim(p_phone),''),p_sector,p_answers,p_sender_hash)
  returning id into v_id;
  return jsonb_build_object('ok',true,'id',v_id,'duplicate',false);
end $$;
revoke all on function public.ms_submit_intake(uuid,text,text,text,text,text,jsonb,text) from public,anon,authenticated;
grant execute on function public.ms_submit_intake(uuid,text,text,text,text,text,jsonb,text) to service_role;

