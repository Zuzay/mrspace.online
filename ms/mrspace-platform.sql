-- Önizlemede insan onayı otomatik yayın izni DEĞİLDİR.
create or replace function public.ms_review_change(p_id bigint,p_decision text,p_proposed text,p_selector text,p_note text)
returns void language plpgsql security definer set search_path = '' as $$
declare v_change public.ms_changes;
begin
  if auth.uid() is null or not public.ms_is_admin() then raise exception 'not_admin'; end if;
  if p_decision is null or p_decision not in ('pending','approved','revision_requested')
    or length(coalesce(p_proposed,''))>10000 or length(coalesce(p_selector,''))>500
    or length(coalesce(p_note,''))>2000 then raise exception 'invalid_review'; end if;
  select * into v_change from public.ms_changes where id=p_id for update;
  if not found or v_change.status in ('done','rejected','withdrawn') or v_change.ai_status='merging' then raise exception 'not_reviewable'; end if;
  if p_decision='revision_requested' and length(trim(coalesce(p_note,'')))<3 then raise exception 'note_required'; end if;
  if p_decision='approved' and (length(trim(coalesce(p_proposed,'')))<1 or length(trim(coalesce(p_selector,'')))<1) then raise exception 'preview_required'; end if;
  insert into public.ms_change_reviews(change_id,decision,proposed,selector,note,reviewed_sha,reviewed_at,released_at,updated_at)
  values(p_id,p_decision,coalesce(p_proposed,''),nullif(p_selector,''),nullif(p_note,''),v_change.pr_head_sha,
    case when p_decision<>'pending' then now() else null end,null,now())
  on conflict(change_id) do update set decision=excluded.decision,proposed=excluded.proposed,
    selector=excluded.selector,note=excluded.note,reviewed_sha=excluded.reviewed_sha,
    reviewed_at=excluded.reviewed_at,released_at=null,updated_at=now();
  insert into public.ms_activity(site,who,action) values(v_change.site,'uzay','Change review: '||p_decision);
end $$;
revoke all on function public.ms_review_change(bigint,text,text,text,text) from public,anon,authenticated;
grant execute on function public.ms_review_change(bigint,text,text,text,text) to authenticated;

-- Kullanıcının ayrıca yayın kararı; hazırlanmış PR'ın incelenen sürümü eşleşmeli.
-- Bu RPC statik yayını veya PR merge işlemini kendisi yapmaz; işçi son SHA kontrolünü yapar.
create or replace function public.ms_release_change(p_id bigint,p_expected_sha text)
returns void language plpgsql security definer set search_path = '' as $$
declare c public.ms_changes; r public.ms_change_reviews;
begin
  if auth.uid() is null or not public.ms_is_admin() then raise exception 'not_admin'; end if;
  select * into c from public.ms_changes where id=p_id for update;
  if not found or c.status not in ('new','approved') or c.ai_status is distinct from 'ready' then raise exception 'not_reviewable'; end if;
  select * into r from public.ms_change_reviews where change_id=p_id for update;
  if r.decision is distinct from 'approved' or p_expected_sha is null
    or p_expected_sha !~ '^[a-f0-9]{40}$' or c.pr_head_sha is distinct from p_expected_sha
    or r.reviewed_sha is distinct from p_expected_sha then raise exception 'review_required'; end if;
  update public.ms_change_reviews set released_at=now() where change_id=p_id;
  perform public.ms_decide_change(p_id,'approved',null);
end $$;
revoke all on function public.ms_release_change(bigint,text) from public,anon,authenticated;
grant execute on function public.ms_release_change(bigint,text) to authenticated;

-- Ayrı işçi süreçleri aynı talebe veya aynı yayın kararına sahip çıkamaz.
create or replace function public.ms_claim_request(p_id bigint)
returns boolean language plpgsql security definer set search_path = '' as $$
begin
  update public.ms_changes set ai_status='working',ai_at=now(),ai_attempts=coalesce(ai_attempts,0)+1
    where id=p_id and status='new' and ai_status is null;
  return found;
end $$;
revoke all on function public.ms_claim_request(bigint) from public,anon,authenticated;
grant execute on function public.ms_claim_request(bigint) to service_role;

create or replace function public.ms_claim_release(p_id bigint,p_sha text)
returns boolean language plpgsql security definer set search_path = '' as $$
declare c public.ms_changes; r public.ms_change_reviews;
begin
  select * into c from public.ms_changes where id=p_id for update;
  if not found or c.status<>'approved' or c.ai_status is distinct from 'ready' then return false; end if;
  select * into r from public.ms_change_reviews where change_id=p_id for update;
  if not found or r.decision<>'approved' or r.released_at is null or p_sha is null or p_sha !~ '^[a-f0-9]{40}$'
    or c.pr_head_sha is distinct from p_sha or r.reviewed_sha is distinct from p_sha then return false; end if;
  update public.ms_changes set ai_status='merging',ai_at=now() where id=p_id;
  return true;
end $$;
revoke all on function public.ms_claim_release(bigint,text) from public,anon,authenticated;
grant execute on function public.ms_claim_release(bigint,text) to service_role;

