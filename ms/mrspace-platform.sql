-- Site üyeliği veya eski gizli talep linki. UUID token yalnızca tekrar korumasıdır;
-- tokenın kendisi bir siteye yetki vermez. Kilit eşzamanlı isteği de tekilleştirir.
create or replace function public.ms_workspace_request(
  p_site text,p_target text,p_request text,p_token uuid,p_key uuid default null
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_site public.ms_sites; v_id bigint; v_count integer;
begin
  if auth.uid() is not null and public.ms_role()='viewer' then raise exception 'not_allowed'; end if;
  select * into v_site from public.ms_sites where slug=p_site for update;
  if not found then raise exception 'not_allowed'; end if;
  if not public.ms_workspace_allowed(p_site) and (p_key is null or p_key is distinct from v_site.site_key) then
    raise exception 'not_allowed';
  end if;
  if p_token is null or p_target is null or p_target not in ('hours','contact','text','photo','design','general')
    or length(trim(coalesce(p_request,'')))<3 or length(p_request)>2000 then raise exception 'invalid_request'; end if;
  select change_id into v_id from public.ms_request_receipts where site=p_site and token=p_token;
  if v_id is not null then return jsonb_build_object('ok',true,'id',v_id,'duplicate',true); end if;
  if v_site.status in ('paused','suspended') then raise exception 'site_paused'; end if;
  select count(*) into v_count from public.ms_changes where site=p_site and created_at>now()-interval '1 hour';
  if v_count>=10 then raise exception 'too_many'; end if;
  insert into public.ms_changes(site,kind,target,request,requested_by)
  values(p_site,case when p_target='design' then 'big' else 'small' end,p_target,trim(p_request),'Workspace')
  returning id into v_id;
  insert into public.ms_request_receipts(site,token,change_id) values(p_site,p_token,v_id);
  insert into public.ms_activity(site,who,action) values(p_site,'client','Workspace request received');
  return jsonb_build_object('ok',true,'id',v_id,'duplicate',false);
end $$;
revoke all on function public.ms_workspace_request(text,text,text,uuid,uuid) from public,anon,authenticated;
grant execute on function public.ms_workspace_request(text,text,text,uuid,uuid) to anon,authenticated;

create or replace function public.ms_queue_draft(p_sector text,p_kind text,p_brief text,p_token uuid)
returns bigint language plpgsql security definer set search_path = '' as $$
declare v_id bigint;
begin
  if auth.uid() is null or not public.ms_is_admin() then raise exception 'not_admin'; end if;
  if p_token is null then raise exception 'invalid_token'; end if;
  perform pg_catalog.pg_advisory_xact_lock(73129410);
  select id into v_id from public.ms_draft_jobs where token=p_token;
  if v_id is not null then return v_id; end if;
  if (select count(*) from public.ms_draft_jobs where created_at>now()-interval '1 hour')>=5 then
    raise exception 'too_many';
  end if;
  insert into public.ms_draft_jobs(sector,kind,brief,token) values(p_sector,p_kind,trim(p_brief),p_token)
  returning id into v_id;
  return v_id;
end $$;
revoke all on function public.ms_queue_draft(text,text,text,uuid) from public,anon,authenticated;
grant execute on function public.ms_queue_draft(text,text,text,uuid) to authenticated;

-- Bir işçi atomik olarak en fazla bir işi alır. Eski işler sonsuz tekrar yapmaz.
create or replace function public.ms_claim_draft()
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_job public.ms_draft_jobs;
begin
  update public.ms_draft_jobs set status='failed',error_code='timeout',finished_at=now()
    where status='working' and started_at<now()-interval '15 minutes';
  select * into v_job from public.ms_draft_jobs where status='queued'
    order by created_at for update skip locked limit 1;
  if not found then return null; end if;
  update public.ms_draft_jobs set status='working',started_at=now() where id=v_job.id returning * into v_job;
  return to_jsonb(v_job)-'token'-'reviewed_by';
end $$;
revoke all on function public.ms_claim_draft() from public,anon,authenticated;
grant execute on function public.ms_claim_draft() to service_role;

-- İşçi çıktısı yayın değildir. HTML sadece operatörün script çalıştırmayan önizlemesine açılır.
create or replace function public.ms_complete_draft(p_id bigint,p_html text,p_error text default null)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if p_error is null and (p_html is null or length(p_html) not between 20 and 1000000) then raise exception 'invalid_artifact'; end if;
  if p_error is not null and p_error !~ '^[a-z0-9_]{1,80}$' then raise exception 'invalid_error'; end if;
  update public.ms_draft_jobs set status=case when p_error is null then 'review' else 'failed' end,
    artifact_html=case when p_error is null then p_html else null end,error_code=p_error,finished_at=now()
    where id=p_id and status='working';
  if not found then raise exception 'not_working'; end if;
end $$;
revoke all on function public.ms_complete_draft(bigint,text,text) from public,anon,authenticated;
grant execute on function public.ms_complete_draft(bigint,text,text) to service_role;

